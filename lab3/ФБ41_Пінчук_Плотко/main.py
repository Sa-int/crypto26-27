from collections import Counter  # Імпортуємо Counter для швидкого підрахунку частот букв і біграм
from itertools import permutations  # Імпортуємо permutations для перебору всіх можливих пар біграм

# Задаємо алфавіт за методичкою (31 буква: без 'ё' та 'ъ', 'ь' стоїть перед 'ы')
ALPHABET = "абвгдежзийклмнопрстуфхцчшщьыэюя"
M = len(ALPHABET)      # Обчислюємо потужність алфавіту m = 31
M2 = M * M             # Обчислюємо модуль для біграм m^2 = 31^2 = 961

# Створюємо словник для переводу кожної букви у її числовий індекс (від 0 до 30)
CHAR_TO_IDX = {ch: i for i, ch in enumerate(ALPHABET)}
# Створюємо зворотний словник для переводу числового індексу назад у букву
IDX_TO_CHAR = {i: ch for i, ch in enumerate(ALPHABET)}

# П'ять найчастіших біграм російської мови згідно з методичними вказівками
LANG_TOP_BIGRAMS = ["ст", "но", "то", "на", "ен"]


# --- 1. МАТЕМАТИЧНИЙ БЛОК (пункт 1 порядку виконання роботи) ---

def extended_gcd(a: int, b: int):
    """Розширений алгоритм Евкліда: знаходить НСД d = gcd(a, b) та коефіцієнти u, v (a*u + b*v = d)."""
    r0, r1 = a, b      # Ініціалізуємо початкові залишки r0 = a та r1 = b
    u0, u1 = 1, 0      # Ініціалізуємо початкові значення послідовності u (u0 = 1, u1 = 0)
    v0, v1 = 0, 1      # Ініціалізуємо початкові значення послідовності v (v0 = 0, v1 = 1)
    while r1 != 0:     # Виконуємо цикл, доки поточний залишок від ділення не стане рівним нулю
        q = r0 // r1   # Обчислюємо цілу частку q від ділення r0 на r1
        r0, r1 = r1, r0 - q * r1  # Оновлюємо залишки за рекурентною формулою алгоритму Евкліда
        u0, u1 = u1, u0 - q * u1  # Оновлюємо коефіцієнти u за рекурентною формулою
        v0, v1 = v1, v0 - q * v1  # Оновлюємо коефіцієнти v за рекурентною формулою
    return r0, u0, v0  # Повертаємо кортеж: НСД (r0) та знайдені коефіцієнти Безу (u0, v0)


def mod_inverse(a: int, n: int):
    """Обчислення оберненого елемента a^(-1) за модулем n."""
    a = a % n                      # Беремо число a за модулем n на випадок від'ємних або великих значень
    d, u, _ = extended_gcd(a, n)   # Викликаємо розширений алгоритм Евкліда для чисел a та n
    if d != 1:                     # Якщо НСД не дорівнює 1, то оберненого елемента не існує
        return None                # Повертаємо None, оскільки число a не є взаємно простим із модулем n
    return u % n                   # Повертаємо знайдений обернений елемент u, приведений за модулем n


def solve_linear_congruence(a: int, b: int, n: int):
    """
    Розв'язування лінійного порівняння a * x = b (mod n).
    Коректно обробляє випадок з одним, декількома або відсутністю розв'язків.
    """
    a = a % n                      # Приводимо коефіцієнт a за модулем n
    b = b % n                      # Приводимо вільний член b за модулем n
    d, _, _ = extended_gcd(a, n)   # Знаходимо найбільший спільний дільник d = gcd(a, n)

    if b % d != 0:                 # Перевіряємо, чи ділиться число b на d без остачі (випадок 2.1)
        return []                  # Якщо b не ділиться на d, порівняння не має жодного розв'язку

    a1 = a // d                    # Ділимо коефіцієнт a на d (отримуємо a1)
    b1 = b // d                    # Ділимо число b на d (отримуємо b1)
    n1 = n // d                    # Ділимо модуль n на d (отримуємо новий модуль n1)

    inv_a1 = mod_inverse(a1, n1)   # Знаходимо обернений елемент до a1 за модулем n1
    if inv_a1 is None:             # Додаткова перевірка на випадок відсутності оберненого елемента
        return []                  # Повертаємо порожній список

    x0 = (b1 * inv_a1) % n1        # Обчислюємо базовий розв'язок x0 = (b1 * a1^(-1)) mod n1
    # Генеруємо та повертаємо всі d розв'язків вигляду x0 + k * n1 (випадок 1 та 2.2)
    return [(x0 + k * n1) % n for k in range(d)]


# --- 2. РОБОТА З БІГРАМАМИ ТА ШИФРОМ ---

def bigram_to_int(bg: str) -> int:
    """Перетворює біграму (рядок з 2 букв) у число за формулою X = x1 * m + x2."""
    return CHAR_TO_IDX[bg[0]] * M + CHAR_TO_IDX[bg[1]]


def int_to_bigram(val: int) -> str:
    """Перетворює число X (від 0 до 960) назад у текстову біграму з 2 букв."""
    return IDX_TO_CHAR[val // M] + IDX_TO_CHAR[val % M]


def clean_text(text: str) -> str:
    """Очищує текст від зайвих символів та приводить його до 31-буквеного алфавіту."""
    text = text.lower().replace("ё", "е").replace("ъ", "ь")  # Переводимо в нижній регістр і замінюємо 'ё' та 'ъ'
    return "".join(ch for ch in text if ch in CHAR_TO_IDX)   # Залишаємо тільки символи, що є в нашому алфавіті


def get_top_bigrams(text: str, top_n: int = 5):
    """Розбиває текст на біграми, що не перетинаються, та повертає top_n найчастіших."""
    bigrams = [text[i:i+2] for i in range(0, len(text) - 1, 2)]  # Нарізаємо текст з кроком 2 на біграми
    counts = Counter(bigrams)                                    # Підраховуємо кількість входжень кожної біграми
    return counts.most_common(top_n)                             # Повертаємо top_n найпопулярніших біграм


def decrypt_affine_bigram(cipher_nums: list[int], a: int, b: int) -> str:
    """Дешифрує список числових біграм шифртексту за допомогою ключа (a, b)."""
    inv_a = mod_inverse(a, M2)             # Знаходимо обернений елемент a^(-1) за модулем m^2 = 961
    if inv_a is None:                      # Якщо оберненого елемента немає, розшифрування неможливе
        return ""                          # Повертаємо порожній рядок
    res = []                               # Створюємо список для збереження розшифрованих біграм
    for y in cipher_nums:                  # Проходимо циклом по кожній числовій біграмі шифртексту Y
        x = (inv_a * (y - b)) % M2         # Обчислюємо біграму відкритого тексту: X = a^(-1) * (Y - b) mod m^2
        res.append(int_to_bigram(x))       # Переводимо число X у дві букви і додаємо до списку результатів
    return "".join(res)                    # Об'єднуємо всі розшифровані біграми в один суцільний рядок


# --- 3. АВТОМАТИЧНИЙ РОЗПІЗНАВАЧ РОСІЙСЬКОЇ МОВИ ---

# Множина заборонених біграм, які не можуть зустрічатися у змістовному тексті (голосна + 'ь' тощо)
FORBIDDEN_BIGRAMS = {
    "аь", "оь", "еь", "иь", "уь", "ыь", "эь", "юь", "яь", "йь", "ьь", "ыы", "йй", "щщ"
}

def is_meaningful_russian(text: str) -> bool:
    """
    Комплексний критерій автоматичного розпізнавання змістовного тексту:
    1. Сумарна частота частих літер ('о', 'е', 'а', 'и') >= 30%
    2. Сумарна частота рідкісних літер ('ф', 'щ', 'ц', 'э') <= 2.5%
    3. Частка заборонених біграм (включно з біграмами на перетині) < 0.5%
    """
    n = len(text)                                           # Визначаємо загальну довжину тексту в символах
    if n == 0:                                              # Якщо текст порожній, він не є змістовним
        return False                                        # Відкидаємо варіант

    counts = Counter(text)                                  # Підраховуємо частоту кожної окремої літери в тексті
    freq_common = sum(counts[ch] for ch in "оеаи") / n      # Обчислюємо сумарну частку найчастіших голосних літер
    freq_rare = sum(counts[ch] for ch in "фщцэ") / n        # Обчислюємо сумарну частку рідкісних літер

    if freq_common < 0.30 or freq_rare > 0.025:             # Якщо частоти не відповідають еталону природної мови
        return False                                        # Відкидаємо текст як випадковий шум

    # Рахуємо кількість заборонених біграм по всьому тексту (крок 1 захоплює і біграми на перетині)
    bad_count = sum(1 for i in range(n - 1) if text[i:i+2] in FORBIDDEN_BIGRAMS)
    if (bad_count / (n - 1)) > 0.005:                       # Якщо частка заборонених біграм перевищує поріг 0.5%
        return False                                        # Відкидаємо текст

    return True                                             # Якщо всі перевірки пройдено — текст є змістовним


# --- 4. ОСНОВНИЙ АЛГОРИТМ КРИПТОАНАЛІЗУ ---

def break_cipher(filename: str):
    """Головна функція криптоаналізу файлу із шифртекстом."""
    print("=" * 70)                                         # Виводимо розділювальну лінію в консоль
    print(f"АНАЛІЗ ФАЙЛУ: {filename}")                      # Виводимо назву файлу, що аналізується
    print("=" * 70)                                         # Виводимо розділювальну лінію

    with open(filename, "r", encoding="utf-8") as f:        # Відкриваємо файл із шифртекстом у кодуванні UTF-8
        raw_text = f.read()                                 # Зчитуємо весь вміст файлу у змінну raw_text

    cipher_text = clean_text(raw_text)                      # Очищуємо зчитаний шифртекст від пробілів та переносів рядків
    # Перетворюємо всі неперетинні біграми шифртексту у список чисел від 0 до 960
    cipher_nums = [bigram_to_int(cipher_text[i:i+2]) for i in range(0, len(cipher_text) - 1, 2)]

    # Крок 2: Знаходимо 5 найчастіших біграм шифртексту
    top_cipher_bgs = get_top_bigrams(cipher_text, 5)        # Отримуємо топ-5 біграм шифртексту та їх кількість
    print("Топ-5 найчастіших біграм шифртексту:")           # Виводимо заголовок таблиці частот
    for bg, cnt in top_cipher_bgs:                          # Проходимо по кожній із 5 найчастіших біграм
        # Виводимо саму біграму, її числовий код, кількість входжень та відсоток у тексті
        print(f"  '{bg}' (код {bigram_to_int(bg):3d}) — {cnt} разів ({cnt / len(cipher_nums) * 100:.2f}%)")

    # Переводимо 5 найчастіших біграм мови у їх числові значення X
    lang_nums = [bigram_to_int(bg) for bg in LANG_TOP_BIGRAMS]
    # Переводимо 5 найчастіших біграм шифртексту у їх числові значення Y
    cipher_top_nums = [bigram_to_int(bg) for bg, _ in top_cipher_bgs]

    # Крок 3: Перебір можливих пар частих біграм мови (X*, X**) та шифртексту (Y*, Y**)
    candidates = set()                                      # Множина для збереження унікальних кандидатів на ключ (a, b)
    multi_solution_cases = 0                                # Лічильник випадків, коли порівняння дає декілька розв'язків

    for x1, x2 in permutations(lang_nums, 2):               # Перебираємо всі можливі впорядковані пари (X*, X**) з топ-5 мови
        for y1, y2 in permutations(cipher_top_nums, 2):     # Перебираємо всі можливі впорядковані пари (Y*, Y**) з топ-5 шифртексту
            dx = (x1 - x2) % M2                             # Обчислюємо різницю відкритих біграм: (X* - X**) mod 961
            dy = (y1 - y2) % M2                             # Обчислюємо різницю шифрованих біграм: (Y* - Y**) mod 961

            # Розв'язуємо лінійне порівняння dx * a = dy (mod 961) відносно невідомого параметра a
            a_solutions = solve_linear_congruence(dx, dy, M2)
            if len(a_solutions) > 1:                        # Якщо порівняння має більше одного розв'язку
                multi_solution_cases += 1                   # Збільшуємо лічильник таких випадків

            for a in a_solutions:                           # Перебираємо всі знайдені розв'язки для параметра a
                # Перевіряємо умову допустимості ключа: a > 0 та gcd(a, 961) = 1 (існує обернений елемент)
                if a > 0 and mod_inverse(a, M2) is not None:
                    b = (y1 - a * x1) % M2                  # Знаходимо відповідний другий параметр ключа: b = (Y* - a*X*) mod 961
                    candidates.add((a, b))                  # Додаємо пару (a, b) до множини кандидатів на ключ

    # Виводимо статистику знайдених кандидатів у консоль
    print(f"\nЗнайдено унікальних допустимих кандидатів на ключ (a, b): {len(candidates)}")
    print(f"Випадків, коли одне співставлення давало декілька розв'язків a: {multi_solution_cases}")

    # Кроки 4-5: Дешифрування шифртексту кожним кандидатом та автоматична перевірка на змістовність
    for a, b in sorted(candidates):                         # Перебираємо всіх унікальних кандидатів (a, b) у відсортованому порядку
        decrypted = decrypt_affine_bigram(cipher_nums, a, b)  # Дешифруємо текст поточним кандидатом на ключ
        if is_meaningful_russian(decrypted):                # Перевіряємо розшифрований текст нашим розпізнавачем мови
            print(f"\n[+] ЗНАЙДЕНО ПРАВИЛЬНИЙ КЛЮЧ: a = {a}, b = {b}")  # Виводимо знайдений правильний ключ
            # Виводимо перші 300 символів розшифрованого відкритого тексту для наочної перевірки
            print(f"[+] Перші 300 символів розшифрованого тексту:\n{decrypted[:300]}...\n")
            
            out_file = f"decrypted_{filename}"              # Формуємо назву вихідного файлу для збереження результату
            with open(out_file, "w", encoding="utf-8") as out:  # Відкриваємо файл на запис у кодуванні UTF-8
                out.write(decrypted)                        # Записуємо повний розшифрований текст у файл
            print(f"[+] Повний розшифрований текст збережено у файл: {out_file}\n")  # Повідомляємо про успішне збереження
            return                                          # Завершуємо роботу функції після знаходження правильного ключа


