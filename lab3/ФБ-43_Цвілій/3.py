# --- 2. Математика ---
def ext_gcd(a: int, b: int):
    if b == 0:
        return a, 1, 0
    d, u1, v1 = ext_gcd(b, a % b)
    return d, v1, u1 - (a // b) * v1


def mod_inverse(a: int, n: int):
    d, u, _ = ext_gcd(a, n)
    if d != 1:
        return None
    return (u % n + n) % n


def solve_linear_congruence(a: int, b: int, n: int):
    a = (a % n + n) % n
    b = (b % n + n) % n
    d, u, _ = ext_gcd(a, n)
    if b % d != 0:
        return []
    a1, b1, n1 = a // d, b // d, n // d
    inv_a1 = mod_inverse(a1, n1)
    if inv_a1 is None:
        return []
    x0 = (b1 * inv_a1) % n1
    return [(x0 + i * n1) % n for i in range(d)]


# --- 3. Біграми та Дешифрування ---
def bigram_to_num(bg: str) -> int:
    return CHAR_TO_IDX[bg[0]] * M + CHAR_TO_IDX[bg[1]]


def num_to_bigram(val: int) -> str:
    return IDX_TO_CHAR[val // M] + IDX_TO_CHAR[val % M]


def decrypt_text(ciphertext: str, a: int, b: int) -> str:
    inv_a = mod_inverse(a, M2)
    if inv_a is None:
        return ""
    res = []
    for i in range(0, len(ciphertext) - 1, 2):
        y = bigram_to_num(ciphertext[i : i + 2])
        x = (inv_a * (y - b)) % M2
        res.append(num_to_bigram(x))
    return "".join(res)


# --- 4. Індекс відповідності ---
def index_of_coincidence(text: str) -> float:
    n = len(text)
    if n <= 1:
        return 0.0
    counts = collections.Counter(text)
    return sum(c * (c - 1) for c in counts.values()) / (n * (n - 1))


