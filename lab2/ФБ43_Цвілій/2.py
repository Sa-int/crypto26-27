def main():
    # --- Підготовка даних та частот ---
    full_cleaned = read_file_safely()
    n_total = len(full_cleaned)
    counts_full = Counter(full_cleaned)
    rus_freqs = {ch: counts_full[ch] / n_total for ch in ALPHABET}
    i_theor = sum(p**2 for p in rus_freqs.values())
    i_rand = 1.0 / M

    print("=== ПІДГОТОВКА ДАНИХ ===")
    print(f"Символів відкритого тексту: {n_total}")
    print(f"I_теор = {i_theor:.5f}")
    print(f"I_випадк = {i_rand:.5f}\n")

    # --- Розділ 1: Дослідження шифру Віженера ---
    print("=== ЧАСТИНА 1. ДОСЛІДЖЕННЯ ШИФРУ ВІЖЕНЕРА ===")
    sample = full_cleaned[: min(n_total, 3000)]
    ic_sample = index_of_coincidence(sample)

    test_keys = ["да", "мир", "лето", "книга", "криптография"]

    print(
        f"{'Текст':<18} | {'Ключ':<15} | {'Довжина r':<10} | {'Індекс I':<10}"
    )
    print("-" * 60)
    print(f"{'Відкритий':<18} | {'-':<15} | {'-':<10} | {ic_sample:.5f}")

    for k in test_keys:
        ct = vigenere_encrypt(sample, k)
        ic_val = index_of_coincidence(ct)
        print(f"{'Шифртекст':<18} | {k:<15} | {len(k):<10} | {ic_val:.5f}")
    print("-" * 60 + "\n")

    # --- Розділ 2: Визначення довжини ключа ---
    print("=== ЧАСТИНА 2. ВИЗНАЧЕННЯ ДОВЖИНИ КЛЮЧА (ВАРІАНТ 3) ===")
    ct = VARIANT_3_CIPHERTEXT
    print(f"Довжина шифртексту: {len(ct)}")
    print(f"I(Y) шифртексту: {index_of_coincidence(ct):.5f}\n")

    print(f"{'r':<4} | {'D_r':<12} | {'Середній I_r':<12} | {'Пік'}")
    print("-" * 40)

    # Поріг відсікання шуму 
    threshold = (i_theor + i_rand) / 2

    stats = []
    peaks = []
    for r in range(2, 31):
        dr = coincidence_count(ct, r)
        avg_ic = avg_block_ic(ct, r)
        
        if avg_ic >= threshold:
            marker = "<-- ПІК"
            peaks.append(r)
        else:
            marker = ""
            
        stats.append((r, dr, avg_ic))
        print(f"{r:<4} | {dr:<12} | {avg_ic:.5f}      | {marker}")
    print("-" * 40)

    # Першим обирається найменший виявлений пік 
    if peaks:
        best_r = peaks[0]
    else:
        best_r = max(stats, key=lambda x: x[2])[0]

    print(f"Обраний період: r = {best_r}\n")

    # --- Розділ 3: Відновлення ключа та дешифрування ---
    print(f"=== ЧАСТИНА 3. ВІДНОВЛЕННЯ КЛЮЧА ТА ТЕКСТУ (r = {best_r}) ===")
    recovered_key = []
    for i in range(best_r):
        col = ct[i::best_r]
        n_col = len(col)
        counts = Counter(col)

        best_k = 0
        best_score = -1.0

        for k in range(M):
            score = 0.0
            for ch, p in rus_freqs.items():
                x_idx = CHAR_TO_IDX[ch]
                cipher_idx = (x_idx + k) % M
                cipher_ch = IDX_TO_CHAR[cipher_idx]
                score += (counts.get(cipher_ch, 0) / n_col) * p

            if score > best_score:
                best_score = score
                best_k = k

        recovered_key.append(IDX_TO_CHAR[best_k])

    key_str = "".join(recovered_key)
    print(f"Відновлений ключ: {key_str}")

    decrypted = vigenere_decrypt(ct, key_str)
    print(f"Фрагмент розшифрованого тексту:\n{decrypted[:200]}\n")

    with open("decrypted_variant3.txt", "w", encoding="utf-8") as f:
        f.write(decrypted)

    # --- Розділ 4: Дослідження впливу помилки в ключі ---
    print("=== ЧАСТИНА 4. ДОСЛІДЖЕННЯ ПОМИЛКИ В КЛЮЧІ ===")
    err_char = "а" if key_str[0] != "а" else "б"
    corrupted_key = err_char + key_str[1:]
    dec_err = vigenere_decrypt(ct, corrupted_key)

    diffs = [i for i in range(len(ct)) if decrypted[i] != dec_err[i]]
    print(f"Правильний ключ: {key_str}")
    print(f"Ключ з помилкою: {corrupted_key}")
    print(
        f"Помилкових символів: {len(diffs)} / {len(ct)} ({len(diffs)/len(ct)*100:.2f}%)"
    )
    print(f"Періодичність помилки: кожен {best_r}-й символ (i % {best_r} == 0)")


if __name__ == "__main__":
    main()