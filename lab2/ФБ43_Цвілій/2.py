CHAR_TO_IDX = {ch: i for i, ch in enumerate(ALPHABET)}
IDX_TO_CHAR = {i: ch for i, ch in enumerate(ALPHABET)}


# --- Функції обробки тексту та шифрування ---
def read_file_safely(candidates=["text.txt", "TEXT", "text.txt.txt"]):
    target_file = None
    for c in candidates:
        if os.path.exists(c):
            target_file = c
            break

    if not target_file:
        for f in os.listdir("."):
            if f.endswith(".txt"):
                target_file = f
                break

    if not target_file:
        raise FileNotFoundError("Файл не знайдено")

    for enc in ["windows-1251", "utf-8", "cp1251", "utf-8-sig"]:
        try:
            with open(target_file, "r", encoding=enc) as f:
                content = f.read()
                cleaned = clean_text(content)
                if len(cleaned) > 1000:
                    return cleaned
        except Exception:
            continue

    raise ValueError("Помилка зчитування файлу")


def clean_text(raw_text: str) -> str:
    raw_text = raw_text.lower().replace("ё", "е")
    return "".join(ch for ch in raw_text if ch in CHAR_TO_IDX)


def index_of_coincidence(text: str) -> float:
    n = len(text)
    if n <= 1:
        return 0.0
    counts = Counter(text)
    numerator = sum(count * (count - 1) for count in counts.values())
    return numerator / (n * (n - 1))


def vigenere_encrypt(plaintext: str, key: str) -> str:
    key = clean_text(key)
    res = []
    r = len(key)
    for i, ch in enumerate(plaintext):
        x = CHAR_TO_IDX[ch]
        k = CHAR_TO_IDX[key[i % r]]
        res.append(IDX_TO_CHAR[(x + k) % M])
    return "".join(res)


def vigenere_decrypt(ciphertext: str, key: str) -> str:
    key = clean_text(key)
    res = []
    r = len(key)
    for i, ch in enumerate(ciphertext):
        y = CHAR_TO_IDX[ch]
        k = CHAR_TO_IDX[key[i % r]]
        res.append(IDX_TO_CHAR[(y - k) % M])
    return "".join(res)


def coincidence_count(ciphertext: str, r: int) -> int:
    return sum(
        1 for i in range(len(ciphertext) - r) if ciphertext[i] == ciphertext[i + r]
    )


def avg_block_ic(ciphertext: str, r: int) -> float:
    blocks = [ciphertext[i::r] for i in range(r)]
    ics = [index_of_coincidence(b) for b in blocks if len(b) > 1]
    return sum(ics) / len(ics) if ics else 0.0


